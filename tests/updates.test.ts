import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFile, spawn } from 'node:child_process';
import { promisify } from 'node:util';
import { AppUpdates, archiveChecksum, compareVersions, parseRelease } from '../electron/updates';
const exec = promisify(execFile);
const repository = 'https://github.com/qixiaoyu27/Mac-Explorer';
const archive = 'Mac-Explorer-0.1.51-mac-arm64.zip';
function release(bytes = 100) { return { tag_name: 'v0.1.51', body: '修复文件浏览\n<script>untrusted()</script>', assets: [archive, 'SHA256SUMS.txt'].map(name => ({ name, size: bytes, browser_download_url: `${repository}/releases/download/v0.1.51/${name}` })) }; }

test('update metadata rejects missing, duplicate, unofficial, prerelease and invalid releases', () => {
  assert.equal(compareVersions('0.1.9', '0.1.50'), -1);
  assert.equal(compareVersions('1.0.0', '0.99.999'), 1);
  assert.equal(compareVersions('0.1.50', '0.1.50'), 0);
  for (const value of ['', '1.2', '1.2.3-beta', '../app', '9999999.0.0']) assert.throws(() => compareVersions(value, '1.0.0'));
  assert.equal(parseRelease(release()).version, '0.1.51');
  for (const value of [null, {}, { ...release(), assets: [] }, { ...release(), prerelease: true }, { ...release(), draft: true }, release(0), release(2 ** 32), { ...release(), assets: [...release().assets, release().assets[0]] }, { ...release(), assets: release().assets.map(a => ({ ...a, browser_download_url: 'https://example.com/payload' })) }]) assert.throws(() => parseRelease(value));
  const checksum = 'a'.repeat(64);
  assert.equal(archiveChecksum(`${checksum}  ${archive}\n`, archive), checksum);
  for (const sums of ['', `invalid ${archive}`, `${checksum} ${archive}\n${checksum} ${archive}`, `${checksum} ../${archive}`]) assert.throws(() => archiveChecksum(sums, archive));
});

test('download verifies signed bundle; successful install leaves no backup and failed install restores original', async t => {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'explorer-update-')));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const applications = path.join(root, 'Applications');
  const target = path.join(applications, 'Mac Explorer.app');
  const source = path.join(root, 'source/Mac Explorer.app');
  await fs.mkdir(path.join(source, 'Contents/MacOS'), { recursive: true });
  const plist = (version: string, id = 'local.macexplorer.desktop') => `<?xml version="1.0"?><plist version="1.0"><dict><key>CFBundleIdentifier</key><string>${id}</string><key>CFBundleVersion</key><string>${version}</string><key>CFBundleShortVersionString</key><string>${version}</string><key>CFBundleExecutable</key><string>Mac Explorer</string><key>CFBundlePackageType</key><string>APPL</string></dict></plist>`;
  await fs.copyFile('/usr/bin/true', path.join(source, 'Contents/MacOS/Mac Explorer'));
  await fs.writeFile(path.join(source, 'Contents/Info.plist'), plist('0.1.50'));
  await exec('/usr/bin/codesign', ['--force', '--deep', '--sign', '-', source]);
  await fs.mkdir(applications); await fs.cp(source, target, { recursive: true });
  const original = await fs.readFile(path.join(target, 'Contents/Info.plist'));
  await fs.writeFile(path.join(source, 'Contents/Info.plist'), plist('0.1.51'));
  const makeZip = async () => {
    await exec('/usr/bin/codesign', ['--force', '--deep', '--sign', '-', source]);
    const zip = path.join(root, archive); await fs.rm(zip, { force: true });
    await exec('/usr/bin/ditto', ['-c', '-k', '--keepParent', source, zip]);
    return fs.readFile(zip);
  };
  let zip = await makeZip();
  let mode = 'ok', requests = 0;
  const mock = t.mock.method(globalThis, 'fetch', async (url: string | URL | Request) => {
    requests++;
    if (mode === 'offline') throw new Error('Network unavailable');
    if (mode === 'rate-limit') return new Response('', { status: 403 });
    if (String(url).endsWith('/latest')) return Response.json(release(zip.length));
    if (String(url).endsWith('SHA256SUMS.txt')) return new Response(`${createHash('sha256').update(zip).digest('hex')}  ${archive}\n`);
    const data = mode === 'corrupt' ? Buffer.alloc(zip.length) : mode === 'truncated' ? zip.subarray(0, 20) : zip;
    return new Response(data);
  });
  t.after(() => mock.mock.restore());
  const states: string[] = [];
  const updater = new AppUpdates('0.1.50', path.join(root, 'cache'), target, path.resolve('scripts/update-install.sh'), state => states.push(state.status));
  assert.equal((await updater.check()).status, 'available');
  assert.equal((await updater.restore()).status, 'available');
  mode = 'corrupt'; assert.equal((await updater.download()).status, 'error');
  assert.match(updater.state.error!, /校验失败/);
  mode = 'truncated'; assert.equal((await updater.download()).status, 'error');
  mode = 'ok';
  const pending = updater.download(); await updater.download();
  assert.equal((await pending).status, 'ready');
  assert.equal((await updater.restore()).status, 'ready');
  assert.equal(updater.state.downloaded, zip.length);
  assert.ok(states.includes('downloading') && states.includes('verifying'));
  const requestCount = requests; await updater.download(); await updater.check(); assert.equal(requests, requestCount);
  assert.deepEqual(await fs.readFile(path.join(target, 'Contents/Info.plist')), original);
  const cache = path.join(root, 'cache');
  const prepared = path.join(cache, (await fs.readdir(cache))[0]);
  await fs.access(path.join(prepared, 'update-install.sh'));
  // Exercise the real detached installer with a temporary parent process; never launch a fixture app.
  const bin = path.join(root, 'bin'); await fs.mkdir(bin);
  await fs.writeFile(path.join(bin, 'pgrep'), '#!/bin/bash\nexit 1\n', { mode: 0o755 });
  await fs.writeFile(path.join(bin, 'mv'), '#!/bin/bash\nif [[ "${TEST_MOVE_FAILURE:-0}" == 1 && "$1" == */.mac-explorer-install.*/"Mac Explorer.app" ]]; then exit 1; fi\nif [[ "${TEST_RESTORE_FAILURE:-0}" == 1 && "$1" == */previous.app ]]; then exit 1; fi\nexec /bin/mv "$@"\n', { mode: 0o755 });
  const installerEnv = { ...process.env, PATH: `${bin}:${process.env.PATH}`, MAC_EXPLORER_PREPARED_UPDATE: prepared, MAC_EXPLORER_INSTALL_DIR: applications, MAC_EXPLORER_NO_OPEN: '1' };
  const sleeper = spawn('/bin/sleep', ['2']);
  const installer = exec('/bin/bash', [path.join(prepared, 'update-install.sh')], { env: { ...installerEnv, MAC_EXPLORER_WAIT_PID: String(sleeper.pid) } });
  await new Promise(resolve => setTimeout(resolve, 300));
  assert.deepEqual(await fs.readFile(path.join(target, 'Contents/Info.plist')), original);
  await installer;
  assert.match(await fs.readFile(path.join(target, 'Contents/Info.plist'), 'utf8'), /0.1.51/);
  assert.equal((await fs.readFile(path.join(prepared, 'result'), 'utf8')).trim(), '0');
  await assert.rejects(fs.access(path.join(applications, '.Mac Explorer Backups')));
  assert.deepEqual((await fs.readdir(applications)).filter(name => name.startsWith('.mac-explorer-install.')), []);
  await exec('/usr/bin/codesign', ['--verify', '--deep', '--strict', target]);
  const fresh = new AppUpdates('0.1.51', cache, target, path.resolve('scripts/update-install.sh'), () => {});
  assert.equal((await fresh.restore()).status, 'idle');
  await assert.rejects(fs.access(path.join(prepared, archive)));
  assert.equal((await fresh.check()).status, 'current');
  await fs.writeFile(path.join(prepared, archive), zip);
  await fs.writeFile(path.join(target, 'Contents/Info.plist'), original);
  await exec('/usr/bin/codesign', ['--force', '--deep', '--sign', '-', target]);
  await assert.rejects(exec('/bin/bash', [path.join(prepared, 'update-install.sh')], { env: { ...installerEnv, MAC_EXPLORER_WAIT_PID: String(sleeper.pid), TEST_MOVE_FAILURE: '1' } }));
  assert.deepEqual(await fs.readFile(path.join(target, 'Contents/Info.plist')), original);
  assert.notEqual((await fs.readFile(path.join(prepared, 'result'), 'utf8')).trim(), '0');
  await assert.rejects(fs.access(path.join(applications, '.Mac Explorer Backups')));
  assert.deepEqual((await fs.readdir(applications)).filter(name => name.startsWith('.mac-explorer-install.')), []);
  await assert.rejects(exec('/bin/bash', [path.join(prepared, 'update-install.sh')], { env: { ...installerEnv, MAC_EXPLORER_WAIT_PID: String(sleeper.pid), TEST_MOVE_FAILURE: '1', TEST_RESTORE_FAILURE: '1' } }));
  const recovery = (await fs.readdir(applications)).filter(name => name.startsWith('.mac-explorer-install.'));
  assert.equal(recovery.length, 1);
  const recoveryFolder = path.join(applications, recovery[0]);
  assert.deepEqual(await fs.readFile(path.join(recoveryFolder, 'previous.app/Contents/Info.plist')), original);
  await assert.rejects(fs.access(target));
  await exec('/bin/mv', [path.join(recoveryFolder, 'previous.app'), target]);
  await fs.rm(recoveryFolder, { recursive: true });
  await fs.writeFile(path.join(prepared, 'install.log'), 'Fixture replacement failed');
  const recovered = new AppUpdates('0.1.50', cache, target, '', () => {});
  assert.equal((await recovered.restore()).status, 'error');
  assert.match(recovered.state.error!, /上次更新未完成/);
  assert.doesNotMatch(recovered.state.error!, /Fixture replacement failed/);
  const newer = new AppUpdates('99.0.0', path.join(root, 'other'), target, '', () => {});
  assert.equal((await newer.check()).status, 'current');
  await assert.rejects(newer.install(process.pid));
  mode = 'offline'; assert.equal((await newer.check()).status, 'error');
  mode = 'rate-limit'; assert.match((await newer.check()).error!, /403/);
  mode = 'ok';
  const dev = new AppUpdates('0.1.50', path.join(root, 'dev'), undefined, '', () => {});
  await dev.check(); assert.equal((await dev.download()).status, 'error');
  assert.equal(dev.state.canInstall, false);
  // A valid checksum cannot make an unrelated or incorrectly versioned bundle installable.
  await fs.writeFile(path.join(source, 'Contents/Info.plist'), plist('0.1.51', 'unrelated.app')); zip = await makeZip();
  const invalid = new AppUpdates('0.1.50', path.join(root, 'invalid'), target, '', () => {});
  await invalid.check(); assert.equal((await invalid.download()).status, 'error');
  assert.match(invalid.state.error!, /不匹配/);
  const linked = path.join(root, 'linked/Mac Explorer.app'); await fs.mkdir(path.dirname(linked)); await fs.symlink(target, linked);
  const symlink = new AppUpdates('0.1.50', path.join(root, 'symlink'), linked, '', () => {});
  await symlink.check(); assert.equal((await symlink.download()).status, 'error');
  assert.match(symlink.state.error!, /可写/);
});
