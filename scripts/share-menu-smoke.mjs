import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import nodeAPIHeaders from 'node-api-headers';

const root = await fs.mkdtemp(path.join(os.tmpdir(), 'explorer-share-'));
const docs = path.join(root, 'Documents');
await fs.mkdir(docs);
const files = ['中文 空格 $test.txt', 'second.md'].map(name => path.join(docs, name));
for (const file of files) await fs.writeFile(file, 'share fixture content');
const fixture = path.join(root, 'share-fixture.node');
execFileSync('xcrun', ['clang++', '-std=c++17', '-fobjc-arc', '-bundle', '-undefined', 'dynamic_lookup', '-framework', 'AppKit', '-DNAPI_VERSION=8', '-I', nodeAPIHeaders.include_dir, 'tests/fixtures/AirDropFixture.mm', '-o', fixture]);
execFileSync('codesign', ['--force', '--sign', '-', fixture]);
const output = path.resolve('artifacts/share-menu');
await fs.mkdir(output, { recursive: true });
let app;
try {
  app = await electron.launch({ colorScheme: null, ...(process.env.EXPLORER_APP_PATH ? { executablePath: process.env.EXPLORER_APP_PATH, args: [] } : { args: [process.cwd()] }), env: { ...process.env, EXPLORER_TEST_LOCALE: 'zh-CN', EXPLORER_TEST_ROOT: root, EXPLORER_TEST_HIDDEN: '1' } });
  const page = await app.firstWindow(); page.setDefaultTimeout(10000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const row = name => page.getByRole('option', { name, exact: true });
  await row('second.md').waitFor();
  // Enumerate the real installed services before replacing delivery with a native fixture.
  const installed = await page.evaluate(files => window.explorer.shareServices(files), files);
  assert.ok(installed.every(service => typeof service.title === 'string' && (!service.icon || service.icon.startsWith('data:image/png;base64,'))));
  console.log(`PASS: live macOS enumeration returned ${installed.length} services without opening a picker.`);
  await app.evaluate(({ ShareMenu }, fixture) => {
    globalThis.nativeSharePopups = 0;
    ShareMenu.prototype.popup = () => { globalThis.nativeSharePopups++; throw new Error('Unexpected native share picker'); };
    const require = process.getBuiltinModule('module').createRequire(process.cwd() + '/package.json');
    globalThis.shareFixture = require(fixture);
  }, fixture);
  const snapshot = () => app.evaluate(() => JSON.parse(globalThis.shareFixture.snapshot()));
  const available = flag => app.evaluate(({}, flag) => globalThis.shareFixture.setAvailable(flag), flag);
  await assert.rejects(page.evaluate(() => window.explorer.shareServices([])), /请选择/);
  await assert.rejects(page.evaluate(() => window.explorer.shareServices(['relative'])), /绝对路径/);
  await assert.rejects(page.evaluate(file => window.explorer.shareServices([file]), path.join(docs, 'missing.txt')), /不存在/);
  for (const service of [null, '', 'bad\0service', 12]) await assert.rejects(page.evaluate(({ files, service }) => window.explorer.share(files, service), { files, service }), /无效/);
  await assert.rejects(page.evaluate(files => window.explorer.share(files, 'missing-service'), files), /重新打开/);
  await row(path.basename(files[0])).click();
  await row('second.md').click({ modifiers: ['Meta'] });
  await row(path.basename(files[0])).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '共享', exact: true }).click();
  await page.getByRole('menuitem', { name: '信息', exact: true }).waitFor();
  assert.deepEqual(await page.getByRole('menuitem').allTextContents(), ['隔空投送', '信息', '备忘录', '无边记']);
  assert.equal((await snapshot()).calls, 0);
  const capture = async name => {
    await page.locator('.context-menu').evaluateAll(menus => Promise.all(menus.flatMap(menu => menu.getAnimations().map(animation => animation.finished))));
    assert.ok(await page.locator('.context-menu button').first().evaluate(button => button.querySelector('.menu-icon').getBoundingClientRect().left - button.getBoundingClientRect().left <= 12), 'Share icons should start near the menu edge without a reserved checkmark column');
    assert.equal(await page.locator('.context-menu').evaluateAll(menus => menus.every(menu => { const r = menu.getBoundingClientRect(); return r.left >= 0 && r.top >= 0 && r.right <= innerWidth && r.bottom <= innerHeight; })), true);
    assert.equal(await page.locator('.menu-icon img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0)), true);
    await page.screenshot({ path: path.join(output, name) });
  };
  await capture('light-fixture.png');
  await page.getByRole('menuitem', { name: '信息', exact: true }).click();
  const sent = await snapshot();
  assert.equal(sent.calls, 1); assert.equal(sent.service, '信息');
  assert.deepEqual(sent.items.map(item => item.path).sort(), [...files].sort());
  assert.ok(sent.items.every(item => item.fileURL));
  await page.evaluate(() => window.explorer.setTheme('dark'));
  const owner = await app.browserWindow(page); await owner.evaluate(window => window.setSize(800, 650));
  await page.waitForFunction(() => innerWidth <= 800 && getComputedStyle(document.body).backgroundColor === 'rgb(25, 25, 25)');
  const toolbarShare = () => page.getByRole('button', { name: '共享', exact: true }).click();
  await toolbarShare(); await page.getByRole('menuitem', { name: '隔空投送', exact: true }).waitFor();
  assert.equal(await page.locator('.context-menu').evaluate(menu => getComputedStyle(menu).backgroundColor), 'rgb(36, 36, 36)');
  await capture('dark-narrow-fixture.png');
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowUp'); await page.keyboard.press('Enter');
  assert.equal((await snapshot()).calls, 2);
  assert.equal((await snapshot()).service, '隔空投送');
  await toolbarShare(); await page.getByRole('menuitem', { name: '信息', exact: true }).waitFor();
  await page.keyboard.press('Escape'); assert.equal(await page.getByRole('menu').count(), 0);
  assert.equal((await snapshot()).calls, 2);
  await toolbarShare(); await page.getByRole('menuitem', { name: '信息', exact: true }).waitFor();
  await available(false);
  await page.getByRole('menuitem', { name: '信息', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '重新打开共享菜单' }).waitFor();
  assert.equal((await snapshot()).calls, 2);
  await page.getByRole('button', { name: '关闭错误提示', exact: true }).click();
  await toolbarShare();
  await page.getByRole('alert').filter({ hasText: '当前没有可用的共享方式' }).waitFor();
  assert.equal(await page.getByRole('menu').count(), 0);
  assert.equal(await app.evaluate(() => globalThis.nativeSharePopups), 0);
  for (const file of files) assert.equal(await fs.readFile(file, 'utf8'), 'share fixture content');
  assert.deepEqual(errors, []);
  console.log('PASS: app-styled context and toolbar Share menus; native service icons; dark/narrow layout; keyboard selection and dismissal; multi-file URLs; invalid/missing paths and service validation; unavailable/stale services; no native picker or real file delivery.');
} finally {
  await app?.close().catch(() => {});
  await fs.rm(root, { recursive: true, force: true, maxRetries: 3 });
}
