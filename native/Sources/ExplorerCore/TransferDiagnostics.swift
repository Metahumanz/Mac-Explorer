import Foundation

/// One bounded report per operation. Paths and error descriptions are never serialized.
public final class TransferDiagnostics: @unchecked Sendable {
  private struct Group: Codable {
    var stage: String
    var depth: Int
    var count = 0
    var failures = 0
    var seconds = 0.0
    var maximumSeconds = 0.0
    var metrics: [String: Double] = [:]
    var codes: [String: [String: Int]] = [:]
  }
  private let lock = NSLock()
  private let started = ProcessInfo.processInfo.systemUptime
  private let identifier = UUID()
  private var groups: [String: Group] = [:]
  private var counters: [URL: (FileTransferMode, Int64)] = [:]
  private var systemBytes: Int64 = 0
  private var serverBytes: Int64 = 0
  public init() {}
  public func record(_ timing: FileTransferTiming) {
    guard timing.stage.utf8.count <= 80, timing.stage.utf8.allSatisfy({ (97...122).contains($0) || $0 == 46 || $0 == 95 }),
      timing.seconds.isFinite, timing.seconds >= 0 else { return }
    lock.lock(); defer { lock.unlock() }
    let key = "\(timing.depth):\(timing.stage)"
    guard groups[key] != nil || groups.count < 64 else { return }
    var group = groups[key] ?? Group(stage: timing.stage, depth: timing.depth)
    group.count += 1; group.failures += timing.succeeded ? 0 : 1
    group.seconds += timing.seconds; group.maximumSeconds = max(group.maximumSeconds, timing.seconds)
    for (name, value) in timing.metrics where value.isFinite && name.utf8.count <= 40 && name.utf8.allSatisfy({ (65...90).contains($0) || (97...122).contains($0) }) {
      if name == "result" || name == "error" {
        if value >= 0 && value <= Double(Int32.max) { group.codes[name, default: [:]][String(Int64(value)), default: 0] += 1 }
      } else { group.metrics[name, default: 0] += value }
    }
    groups[key] = group
  }
  public func progress(_ value: FileTransferProgress) {
    lock.lock(); defer { lock.unlock() }
    let previous = counters[value.source]
    let baseline = previous?.0 == value.mode ? previous?.1 ?? 0 : 0
    let delta = max(0, value.completedBytes - baseline)
    if value.mode == .serverSide { serverBytes += delta } else { systemBytes += delta }
    // Progress is serial; keep only its current source, never an unbounded file list.
    counters = [value.source: (value.mode, max(0, value.completedBytes))]
  }
  /// Called on the background worker, once the result is known.
  @discardableResult public func finish(_ result: FileActionResult, directory: URL) throws -> URL {
    lock.lock()
    let stages = groups.values.sorted { ($0.depth, $0.stage) < ($1.depth, $1.stage) }
    let local = systemBytes, remote = serverBytes
    lock.unlock()
    struct Report: Encodable {
      let schema = 1
      let operation: UUID
      let timestamp: Date
      let elapsedSeconds: Double
      let systemAcknowledgedBytes: Int64
      let serverAcknowledgedBytes: Int64
      let outcomes: [String: Int]
      let methods: [String: Int]
      let errorCount: Int
      let stages: [Group]
    }
    let report = Report(operation: identifier, timestamp: Date(), elapsedSeconds: ProcessInfo.processInfo.systemUptime - started,
      systemAcknowledgedBytes: local, serverAcknowledgedBytes: remote,
      outcomes: Dictionary(grouping: result.transfers, by: { $0.outcome.rawValue }).mapValues(\.count),
      methods: Dictionary(grouping: result.transfers, by: { $0.method.rawValue }).mapValues(\.count),
      errorCount: result.errors.count, stages: stages)
    let encoder = JSONEncoder(); encoder.outputFormatting = [.prettyPrinted, .sortedKeys]; encoder.dateEncodingStrategy = .iso8601
    let fm = FileManager.default
    try fm.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
    let destination = directory.appendingPathComponent("transfer-\(identifier.uuidString).json")
    try encoder.encode(report).write(to: destination, options: .atomic)
    // Only prune names generated by this collector, never arbitrary cache files.
    let owned = try fm.contentsOfDirectory(at: directory, includingPropertiesForKeys: [.contentModificationDateKey]).filter {
      let name = $0.lastPathComponent
      return name.hasPrefix("transfer-") && name.hasSuffix(".json") && UUID(uuidString: String(name.dropFirst(9).dropLast(5))) != nil
    }.sorted {
      let a = (try? $0.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate) ?? .distantPast
      let b = (try? $1.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate) ?? .distantPast
      return a > b
    }
    for file in owned.dropFirst(20) { try? fm.removeItem(at: file) }
    return destination
  }
}
